import { chromium } from "playwright";
import { mkdir } from "node:fs/promises";
import assert from "node:assert/strict";
import pino from "pino";
const logger = pino();
const main = async (): Promise<void> => {
  const browser = await chromium.launch({ headless: true });
  const errors: string[] = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto("http://127.0.0.1:3000", { waitUntil: "domcontentloaded" });
    await page.locator(".listing-card").first().waitFor({ timeout: 20_000 });
    assert.equal(await page.getByText("Маршрут уточняется", { exact: true }).count(), 0);
    const ratingValues = await page.locator(".listing-card .rating strong").allTextContents();
    assert.ok(ratingValues.every((value) => value.trim() !== "—"), "Missing scores must show an explicit state");
    await page.waitForFunction(() => Array.from(document.querySelectorAll<HTMLImageElement>(".listing-image img")).some((img) => img.complete && img.naturalWidth > 0), undefined, { timeout: 15_000 }).catch(() => logger.warn("Listing CDN images are not yet available"));
    await mkdir("artifacts", { recursive: true });
    await page.screenshot({ path: "artifacts/catalog-desktop.png" });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.getByRole("spinbutton", { name: "Цена, $: до", exact: true }).fill("70000");
    await page.waitForResponse((r) => r.url().includes("/api/listings?") && decodeURIComponent(r.url()).includes("70000"));
    assert.ok(new URL(page.url()).searchParams.get("filters")?.includes("70000"));
    await page.getByTitle("Сбросить фильтры").click();
    await page.locator(".listing-card").first().getByRole("button", { name: /Открыть/ }).click();
    await page.getByRole("heading", { name: "Характеристики", exact: true }).waitFor();
    await page.screenshot({ path: "artifacts/catalog-detail.png" });
    await page.getByTitle("Закрыть", { exact: true }).click();
    const mapResponse = page.waitForResponse((r) => r.url().includes("/api/map?") && r.status() === 200);
    await page.getByRole("button", { name: "Карта", exact: true }).click();
    await mapResponse;
    await page.locator(".leaflet-container").waitFor();
    await page.locator(".leaflet-tile-loaded").first().waitFor({ timeout: 15000 });
    await page.locator(".cluster-count").first().waitFor({ timeout: 5000 });
    await page.screenshot({ path: "artifacts/catalog-map.png" });
    await page.getByRole("button", { name: "Настройки", exact: true }).click();
    await page.getByRole("heading", { name: "Вес параметров удобства" }).waitFor();
    await page.getByRole("button", { name: "Фоновые задачи", exact: true }).click();
    await page.getByRole("heading", { name: "Состояние сбора" }).waitFor();
    await page.getByRole("heading", { name: "Фоновые задачи" }).waitFor();
    await page.getByRole("columnheader", { name: "В работе" }).or(page.getByText("Фоновых задач нет.")).waitFor();
    await page.screenshot({ path: "artifacts/catalog-sources.png" });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "Background tasks mobile overflow");
    await page.getByRole("button", { name: "Каталог", exact: true }).click();
    await page.getByRole("button", { name: "Список", exact: true }).click();
    await page.locator(".listing-card").first().waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "Mobile overflow");
    await page.screenshot({ path: "artifacts/catalog-mobile.png" });
    await page.getByRole("button", { name: "Фильтры", exact: true }).click();
    await page.getByRole("spinbutton", { name: "Цена, $: до", exact: true }).waitFor({ state: "visible" });
    assert.deepEqual(errors, []);
    logger.info({ screenshots: 5 }, "Catalog browser smoke checks passed");
  } finally { await browser.close(); }
};
void main().catch((error: unknown) => { logger.error({ err: error }, "Browser smoke failed"); process.exitCode = 1; });
